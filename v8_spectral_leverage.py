def build_comparative_states(
    target: MechanicalState,
    target_random: MechanicalState,
    cfg: Config,
    rng: np.random.Generator,
) -> Tuple[
    MechanicalState,
    MechanicalState,
    MechanicalState,
    np.ndarray,
    Tuple[float, float, float, float],
]:

    # ---- Native top-leverage ablation ----
    (
        top_edges,
        _top_removed,
        top_delta,
        top_lambda,
    ) = top_leverage_ablation(
        target,
        cfg.top_ablation_fraction,
        cfg,
    )

    target_top = make_mechanical_state(
        "Target_top5pct_ablation",
        target.coords_A,
        top_edges,
        cfg,
    )

    # ---- Null-top-leverage ablation ----
    (
        null_top_edges,
        _null_top_removed,
        null_top_delta,
        null_top_lambda,
    ) = top_leverage_ablation(
        target_random,
        cfg.top_ablation_fraction,
        cfg,
    )

    null_top = make_mechanical_state(
        "Null_top5pct_ablation",
        target_random.coords_A,
        null_top_edges,
        cfg,
    )

    # ---- Random ablation null ensemble ----
    random_deltas = random_ablation_ensemble(
        target,
        cfg.top_ablation_fraction,
        cfg.random_ablation_runs,
        rng,
        cfg,
    )

    # Representative random-ablation trajectory:
    # use a random realization close to the median delta.
    m = target.edges.shape[0]

    remove_n = max(
        1,
        int(np.ceil(
            cfg.top_ablation_fraction * m
        )),
    )

    baseline_lambda = (
        smallest_positive_eigenvalue(
            target.hessian,
            cfg,
        )
    )

    candidates = []

    for _ in range(
        max(
            10,
            cfg.random_ablation_runs
        )
    ):

        remove_indices = rng.choice(
            m,
            size=remove_n,
            replace=False,
        )

        edges_candidate = ablate_edges(
            target.edges,
            remove_indices,
        )

        h_candidate = build_enm_hessian(
            target.coords_A,
            edges_candidate,
            cfg.spring_k,
        )

        lambda_candidate = (
            smallest_positive_eigenvalue(
                h_candidate,
                cfg,
            )
        )

        delta_candidate = (
            lambda_candidate
            - baseline_lambda
        )

        candidates.append(
            (
                delta_candidate,
                edges_candidate,
            )
        )

    median_delta = float(
        np.median(
            random_deltas
        )
    )

    candidates.sort(
        key=lambda item:
        abs(
            item[0]
            - median_delta
        )
    )

    representative_random_edges = (
        candidates[0][1]
    )

    target_random_ablation = (
        make_mechanical_state(
            "Target_random5pct_ablation",
            target.coords_A,
            representative_random_edges,
            cfg,
        )
    )

    metadata = (
        top_delta,
        top_lambda,
        null_top_delta,
        null_top_lambda,
    )

    return (
        target_top,
        null_top,
        target_random_ablation,
        random_deltas,
        metadata,
    )


