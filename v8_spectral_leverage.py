def histogram_density(
    values: np.ndarray,
    bins: np.ndarray,
) -> np.ndarray:

    counts, _ = np.histogram(
        values,
        bins=bins,
        density=False,
    )

    widths = np.diff(bins)

    density = (
        counts.astype(float)
        / max(
            float(np.sum(counts)),
            1.0,
        )
        / widths
    )

    area = float(
        np.sum(
            density * widths
        )
    )

    if area <= 0.0:
        raise RuntimeError(
            "Could not normalize density."
        )

    return density / area


def total_variation_from_hist(
    p: np.ndarray,
    q: np.ndarray,
    bins: np.ndarray,
) -> float:

    widths = np.diff(
        bins
    )

    return float(
        0.5
        * np.sum(
            np.abs(p - q)
            * widths
        )
    )


def prepare_common_leverage_density(
    states: List[MechanicalState],
    cfg: Config,
) -> Tuple[
    np.ndarray,
    Dict[str, np.ndarray],
]:

    pooled = np.concatenate(
        [
            state.leverage
            for state in states
        ]
    )

    lo = float(
        np.min(pooled)
    )

    hi = float(
        np.max(pooled)
    )

    if hi <= lo:
        hi = lo + 1.0

    margin = 0.05 * (
        hi - lo
    )

    bins = np.linspace(
        max(
            0.0,
            lo - margin,
        ),
        hi + margin,
        cfg.density_bins + 1,
    )

    densities = {
        state.name:
        histogram_density(
            state.leverage,
            bins,
        )
        for state in states
    }

    return bins, densities


def gamma_from_tv(
    tv_distance: float,
    cfg: Config,
) -> float:
    """
    Monotone phenomenological closure:

        gamma_eff =
            gamma_floor
            + gamma_span * TV

    This is NOT a first-principles microscopic
    radical-pair rate law.
    """

    tv_bounded = float(
        np.clip(
            tv_distance,
            0.0,
            1.0,
        )
    )

    return (
        cfg.gamma_floor_per_us
        + cfg.gamma_span_per_us
        * tv_bounded
    )


# ============================================================
# 4x4 ELECTRON SPIN MODEL
# ============================================================

def single_spin_z() -> np.ndarray:
    return 0.5 * np.array(
        [
            [1.0, 0.0],
            [0.0, -1.0],
        ],
        dtype=complex,
    )


def identity_2() -> np.ndarray:
    return np.eye(
        2,
        dtype=complex,
    )


def singlet_triplet_basis() -> np.ndarray:
    up = np.array(
        [1.0, 0.0],
        dtype=complex,
    )

    down = np.array(
        [0.0, 1.0],
        dtype=complex,
    )

    uu = np.kron(
        up,
        up,
    )

    ud = np.kron(
        up,
        down,
    )

    du = np.kron(
        down,
        up,
    )

    dd = np.kron(
        down,
        down,
    )

    singlet = (
        ud - du
    ) / np.sqrt(2.0)

    triplet_0 = (
        ud + du
    ) / np.sqrt(2.0)

    triplet_plus = uu
    triplet_minus = dd

    # Column order:
    #   S, T+, T0, T-
    return np.column_stack(
        (
            singlet,
            triplet_plus,
            triplet_0,
            triplet_minus,
        )
    )


def build_spin_hamiltonian(
    cfg: Config,
) -> Tuple[
    np.ndarray,
    np.ndarray,
    List[np.ndarray],
]:
    """
    Standalone 4x4 electron-only closure.

    Product basis Hamiltonian:
        H =
        omega_B(S1z + S2z)
        + A1*S1z
        + A2*S2z

    It is intentionally an effective toy closure:
    no explicit nuclear Hilbert space is included.
    """

    sz = single_spin_z()
    ident = identity_2()

    s1z = np.kron(
        sz,
        ident,
    )

    s2z = np.kron(
        ident,
        sz,
    )

    omega_B = (
        cfg.electron_gyromagnetic_rad_s_T
        * cfg.earth_B_T
        * 1e-6
    )

    A1 = (
        2.0
        * np.pi
        * cfg.hyperfine_A1_MHz
    )

    A2 = (
        2.0
        * np.pi
        * cfg.hyperfine_A2_MHz
    )

    H_product = (
        omega_B
        * (s1z + s2z)
        + A1 * s1z
        + A2 * s2z
    )

    U = singlet_triplet_basis()

    H_st = (
        U.conj().T
        @ H_product
        @ U
    )

    # Singlet projector.
    P_S = np.zeros(
        (4, 4),
        dtype=complex,
    )

    P_S[0, 0] = 1.0

    # Jump channels:
    # |S> -> |T+>, |T0>, |T->
    jump_ops = []

    for triplet_index in (
        1,
        2,
        3,
    ):
        jump = np.zeros(
            (4, 4),
            dtype=complex,
        )

        jump[
            triplet_index,
            0
        ] = 1.0

        jump_ops.append(jump)

    return (
        H_st,
        P_S,
        jump_ops,
    )


# ============================================================
# LINDBLAD DYNAMICS
# ============================================================

def lindblad_rhs(
    rho: np.ndarray,
    H: np.ndarray,
    jump_ops: List[np.ndarray],
    gamma_eff: float,
) -> np.ndarray:

    commutator = (
        H @ rho
        - rho @ H
    )

    drho = -1j * commutator

    if gamma_eff > 0.0:

        for jump in jump_ops:

            jump_scaled = (
                np.sqrt(
                    gamma_eff / 3.0
                )
                * jump
            )

            jump_dag_jump = (
                jump_scaled.conj().T
                @ jump_scaled
            )

            drho += (
                jump_scaled
                @ rho
                @ jump_scaled.conj().T
                - 0.5
                * (
                    jump_dag_jump @ rho
                    + rho @ jump_dag_jump
                )
            )

    return drho


def positivity_guard(
    rho: np.ndarray,
) -> np.ndarray:
    """
    Numerical physical-state projection:

    1. Hermitize
    2. Normalize trace
    3. Diagonalize rho
    4. Clip tiny negative eigenvalues
    5. Renormalize trace

    This is a numerical safeguard, not a new
    physical term in the Lindblad generator.
    """

    rho = 0.5 * (
        rho + rho.conj().T
    )

    trace = float(
        np.real(
            np.trace(rho)
        )
    )

    if trace <= 0.0:
        raise RuntimeError(
            "Density-matrix trace became nonpositive."
        )

    rho /= trace

    values, vectors = la.eigh(
        rho,
        check_finite=True,
    )

    values = np.maximum(
        values,
        0.0,
    )

    total = float(
        np.sum(values)
    )

    if total <= 0.0:
        raise RuntimeError(
            "Positivity projection produced zero trace."
        )

    rho = (
        vectors
        * values
    ) @ vectors.conj().T

    rho = 0.5 * (
        rho + rho.conj().T
    )

    rho /= np.real(
        np.trace(rho)
    )

    return rho


def integrate_lindblad(
    gamma_eff: float,
    cfg: Config,
    H: np.ndarray,
    P_S: np.ndarray,
    jump_ops: List[np.ndarray],
) -> Tuple[
    np.ndarray,
    np.ndarray,
]:

    steps = int(
        round(
            cfg.lindblad_total_time_us
            / cfg.lindblad_dt_us
        )
    )

    if steps <= 0:
        raise ValueError(
            "Lindblad integration requires "
            "a positive number of steps."
        )

    times = np.linspace(
        0.0,
        cfg.lindblad_total_time_us,
        steps + 1,
    )

    # Initial state = pure singlet.
    rho = P_S.copy()

    Y_S = np.empty(
        steps + 1,
        dtype=float,
    )

    Y_S[0] = float(
        np.real(
            np.trace(
                P_S @ rho
            )
        )
    )

    dt = cfg.lindblad_dt_us

    for step in range(steps):

        # Explicit RK4 loop.
        k1 = lindblad_rhs(
            rho,
            H,
            jump_ops,
            gamma_eff,
        )

        k2 = lindblad_rhs(
            rho + 0.5 * dt * k1,
            H,
            jump_ops,
            gamma_eff,
        )

        k3 = lindblad_rhs(
            rho + 0.5 * dt * k2,
            H,
            jump_ops,
            gamma_eff,
        )

        k4 = lindblad_rhs(
            rho + dt * k3,
            H,
            jump_ops,
            gamma_eff,
        )

        rho = rho + (
            dt / 6.0
        ) * (
            k1
            + 2.0 * k2
            + 2.0 * k3
            + k4
        )

        # Numerical physical-state guard.
        rho = positivity_guard(
            rho
        )

        trace_error = abs(
            np.trace(rho) - 1.0
        )

        hermiticity_error = np.max(
            np.abs(
                rho - rho.conj().T
            )
        )

        min_density_eigenvalue = float(
            np.min(
                la.eigvalsh(rho)
            )
        )

        if (
            trace_error > 1e-10
            or hermiticity_error > 1e-10
            or min_density_eigenvalue < -1e-10
        ):
            raise FloatingPointError(
                "Density-matrix guard failed "
                f"at step {step}: "
                f"trace={trace_error:.3e}, "
                f"hermiticity={hermiticity_error:.3e}, "
                f"min_eig={min_density_eigenvalue:.3e}"
            )

        Y_S[step + 1] = float(
            np.real(
                np.trace(
                    P_S @ rho
                )
            )
        )

    return (
        times,
        Y_S,
    )


