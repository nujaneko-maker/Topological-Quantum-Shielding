def generate_spiral_fold(
    n: int,
    turns: float,
    radius_A: float,
    pitch_A_per_rad: float,
    phase_rad: float,
    radial_modulation: float,
    axial_warp_A: float,
    axial_warp_freq: float,
    radial_warp_freq: float,
) -> np.ndarray:
    """
    Deterministic 3D spiral/polymer-like fold.

    This is deliberately synthetic:
    it replaces PDB I/O so the experiment is standalone and reproducible.
    """
    t = np.linspace(
        0.0,
        turns * 2.0 * np.pi,
        n,
        dtype=float,
    )

    r = radius_A * (
        1.0
        + radial_modulation
        * np.sin(radial_warp_freq * t + phase_rad)
    )

    x = r * np.cos(t + phase_rad)
    y = r * np.sin(t + phase_rad)

    z = (
        pitch_A_per_rad * t
        + axial_warp_A
        * np.sin(axial_warp_freq * t + 0.3 * phase_rad)
    )

    coords = np.column_stack((x, y, z))

    # Remove global translation only.
    coords -= coords.mean(axis=0, keepdims=True)

    return coords


