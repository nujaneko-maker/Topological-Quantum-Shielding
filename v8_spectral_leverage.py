# 3D ENM HESSIAN
# ============================================================

def build_enm_hessian(
    coords_A: np.ndarray,
    edges: np.ndarray,
    spring_k: float,
) -> np.ndarray:
    """
    Central-force 3D ENM/ANM-type Hessian:

        H_ii += k P_ij
        H_jj += k P_ij
        H_ij -= k P_ij
        H_ji -= k P_ij

    where
        P_ij = u_ij u_ij^T
    """

    n = coords_A.shape[0]
    dim = 3 * n

    h = np.zeros(
        (dim, dim),
        dtype=float,
    )

    ri = coords_A[edges[:, 0]]
    rj = coords_A[edges[:, 1]]

    delta = rj - ri

    norms = np.linalg.norm(
        delta,
        axis=1,
    )

    if np.any(norms <= 0.0):
        raise ValueError(
            "Zero-length edge encountered."
        )

    unit_vectors = delta / norms[:, None]

    projectors = spring_k * np.einsum(
        "ea,eb->eab",
        unit_vectors,
        unit_vectors,
    )

    local_i = (
        3 * edges[:, 0, None]
        + np.arange(3)[None, :]
    )

    local_j = (
        3 * edges[:, 1, None]
        + np.arange(3)[None, :]
    )

    ii_rows = np.broadcast_to(
        local_i[:, :, None],
        projectors.shape,
    )

    ii_cols = np.broadcast_to(
        local_i[:, None, :],
        projectors.shape,
    )

    jj_rows = np.broadcast_to(
        local_j[:, :, None],
        projectors.shape,
    )

    jj_cols = np.broadcast_to(
        local_j[:, None, :],
        projectors.shape,
    )

    np.add.at(
        h,
        (
            ii_rows.ravel(),
            ii_cols.ravel(),
        ),
        projectors.ravel(),
    )

    np.add.at(
        h,
        (
            jj_rows.ravel(),
            jj_cols.ravel(),
        ),
        projectors.ravel(),
    )

    np.add.at(
        h,
        (
            ii_rows.ravel(),
            jj_cols.ravel(),
        ),
        -projectors.ravel(),
    )

    np.add.at(
        h,
        (
            jj_rows.ravel(),
            ii_cols.ravel(),
        ),
        -projectors.ravel(),
    )

    # Numerical symmetrization only.
    h = 0.5 * (h + h.T)

    return h


