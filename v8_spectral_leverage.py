# CONTACT GRAPH
# ============================================================

def contact_graph(
    coords_A: np.ndarray,
    cutoff_A: float,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Strict spatial contact rule:
        ||r_i-r_j|| <= cutoff_A
    """
    diff = coords_A[:, None, :] - coords_A[None, :, :]
    dist2 = np.einsum("ijk,ijk->ij", diff, diff)

    upper_i, upper_j = np.triu_indices(
        coords_A.shape[0],
        k=1,
    )

    mask = dist2[upper_i, upper_j] <= cutoff_A * cutoff_A

    edges = np.column_stack(
        (upper_i[mask], upper_j[mask])
    ).astype(int, copy=False)

    distances = np.sqrt(
        dist2[upper_i[mask], upper_j[mask]]
    )

    adjacency = np.zeros(
        (coords_A.shape[0], coords_A.shape[0]),
        dtype=bool,
    )

    adjacency[
        edges[:, 0],
        edges[:, 1]
    ] = True

    adjacency[
        edges[:, 1],
        edges[:, 0]
    ] = True

    return edges, distances, adjacency


def degree_sequence(
    edges: np.ndarray,
    n: int,
) -> np.ndarray:
    deg = np.bincount(
        edges.reshape(-1),
        minlength=n,
    )

    return deg.astype(
        int,
        copy=False,
    )


# ============================================================
# DEGREE-PRESERVING MASLOV–SNEPPEN NULL
# ============================================================

def degree_preserving_maslov_sneppen(
    edges: np.ndarray,
    n: int,
    swaps_per_edge: int,
    max_attempt_factor: int,
    rng: np.random.Generator,
) -> Tuple[np.ndarray, int, int]:
    """
    Topology-only null ensemble.

    Important:
    - degree sequence is preserved exactly
    - edge count is preserved exactly
    - node labels are preserved
    - spatial geometry is NOT used as an acceptance constraint

    Thus the null intentionally destroys native spatial contact organization.
    This is a topology-null, not a physically realistic protein conformation.
    """

    if edges.size == 0:
        raise ValueError("Cannot randomize an empty graph.")

    edge_list = [
        tuple(map(int, e))
        for e in edges
    ]

    edge_set = set(edge_list)

    def canonical(a: int, b: int) -> Tuple[int, int]:
        return (a, b) if a < b else (b, a)

    target_accepts = max(
        swaps_per_edge * len(edge_list),
        20,
    )

    max_attempts = max(
        target_accepts * max_attempt_factor,
        10000,
    )

    accepted = 0
    attempts = 0

    while (
        accepted < target_accepts
        and attempts < max_attempts
    ):
        attempts += 1

        e1_idx, e2_idx = rng.choice(
            len(edge_list),
            size=2,
            replace=False,
        )

        a, b = edge_list[e1_idx]
        c, d = edge_list[e2_idx]

        # Standard double-edge swap requires 4 distinct nodes.
        if len({a, b, c, d}) < 4:
            continue

        if rng.random() < 0.5:
            new1 = canonical(a, d)
            new2 = canonical(c, b)
        else:
            new1 = canonical(a, c)
            new2 = canonical(b, d)

        # No self loops.
        if (
            new1[0] == new1[1]
            or new2[0] == new2[1]
        ):
            continue

        # No duplicate edges.
        if (
            new1 in edge_set
            or new2 in edge_set
        ):
            continue

        old1 = canonical(a, b)
        old2 = canonical(c, d)

        edge_set.remove(old1)
        edge_set.remove(old2)

        edge_set.add(new1)
        edge_set.add(new2)

        edge_list[e1_idx] = new1
        edge_list[e2_idx] = new2

        accepted += 1

    if accepted < target_accepts:
        raise RuntimeError(
            "Maslov-Sneppen rewiring stalled: "
            f"accepted={accepted}, "
            f"target={target_accepts}, "
            f"attempts={attempts}"
        )

    randomized = np.array(
        sorted(edge_set),
        dtype=int,
    )

    if randomized.shape != edges.shape:
        raise RuntimeError(
            "Degree-preserving rewiring changed edge count."
        )

    # Sanity-check node bounds.
    if (
        np.min(randomized) < 0
        or np.max(randomized) >= n
    ):
        raise RuntimeError(
            "Randomized graph contains an invalid node index."
        )

    return randomized, accepted, attempts


