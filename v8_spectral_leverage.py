# EIGENVALUE DIAGONALIZATION / RIGID-BODY SCRUB
# ============================================================

def rigid_body_zero_tolerance(
    eigenvalues: np.ndarray,
    cfg: Config,
) -> float:
    scale = max(
        1.0,
        float(np.max(np.abs(eigenvalues))),
    )

    return max(
        cfg.eig_abs_tol,
        cfg.eig_rel_tol * scale,
    )


def diagonalize_and_scrub(
    hessian: np.ndarray,
    cfg: Config,
) -> Tuple[
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
    float,
]:
    """
    Full symmetric eigendecomposition:
        H v_k = lambda_k v_k

    Expected central-force rigid-body nullspace:
        3 translations + 3 rotations = 6 modes.
    """

    eigenvalues, eigenvectors = la.eigh(
        hessian,
        check_finite=True,
        overwrite_a=False,
    )

    tol = rigid_body_zero_tolerance(
        eigenvalues,
        cfg,
    )

    # ENM central-force Hessian should be PSD up to roundoff.
    min_eval = float(np.min(eigenvalues))

    if min_eval < -10.0 * tol:
        raise RuntimeError(
            "Hessian is not positive-semidefinite "
            f"within tolerance: min={min_eval:.3e}"
        )

    required_modes = (
        cfg.mode_start_full_index
        + cfg.soft_mode_count
        + 1
    )

    if eigenvalues.shape[0] < required_modes:
        raise RuntimeError(
            "Matrix is too small for requested soft-mode window."
        )

    # Explicit six-mode rigid-body check.
    rigid = eigenvalues[
        :cfg.mode_start_full_index
    ]

    if not np.all(
        np.abs(rigid) <= 10.0 * tol
    ):
        raise RuntimeError(
            "Expected six rigid-body modes at "
            "the bottom of the spectrum, but found:\n"
            f"{rigid}"
        )

    positive_mask = eigenvalues > tol

    positive_eigenvalues = eigenvalues[
        positive_mask
    ]

    positive_eigenvectors = eigenvectors[
        :,
        positive_mask
    ]

    if (
        positive_eigenvalues.size
        < cfg.soft_mode_count
    ):
        raise RuntimeError(
            "Insufficient positive modes after "
            "rigid-body scrubbing."
        )

    return (
        eigenvalues,
        eigenvectors,
        positive_eigenvalues,
        positive_eigenvectors,
        tol,
    )


