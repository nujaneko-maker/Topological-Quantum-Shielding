def ablate_edges(
    edges: np.ndarray,
    removed_indices: np.ndarray,
) -> np.ndarray:
    mask = np.ones(
        edges.shape[0],
        dtype=bool,
    )

    mask[
        np.asarray(
            removed_indices,
            dtype=int,
        )
    ] = False

    ablated = edges[mask]

    if ablated.shape[0] == 0:
        raise RuntimeError(
            "Ablation removed all edges."
        )

    return ablated


def smallest_positive_eigenvalue(
    hessian: np.ndarray,
    cfg: Config,
) -> float:

    eigenvalues = la.eigvalsh(
        hessian,
        check_finite=True,
        overwrite_a=False,
    )

    tol = rigid_body_zero_tolerance(
        eigenvalues,
        cfg,
    )

    positive = eigenvalues[
        eigenvalues > tol
    ]

    if positive.size == 0:
        return float("nan")

    return float(
        positive[0]
    )


def top_leverage_ablation(
    state: MechanicalState,
    fraction: float,
    cfg: Config,
) -> Tuple[
    np.ndarray,
    np.ndarray,
    float,
    float,
]:

    m = state.edges.shape[0]

    remove_n = max(
        1,
        int(np.ceil(
            fraction * m
        )),
    )

    order = np.argsort(
        state.leverage
    )[::-1]

    remove_indices = order[
        :remove_n
    ]

    ablated_edges = ablate_edges(
        state.edges,
        remove_indices,
    )

    ablated_hessian = build_enm_hessian(
        state.coords_A,
        ablated_edges,
        cfg.spring_k,
    )

    lambda_native = (
        smallest_positive_eigenvalue(
            state.hessian,
            cfg,
        )
    )

    lambda_ablated = (
        smallest_positive_eigenvalue(
            ablated_hessian,
            cfg,
        )
    )

    delta_lambda = (
        lambda_ablated
        - lambda_native
    )

    return (
        ablated_edges,
        remove_indices,
        delta_lambda,
        lambda_ablated,
    )


def random_ablation_ensemble(
    state: MechanicalState,
    fraction: float,
    runs: int,
    rng: np.random.Generator,
    cfg: Config,
) -> np.ndarray:

    m = state.edges.shape[0]

    remove_n = max(
        1,
        int(np.ceil(
            fraction * m
        )),
    )

    lambda_native = (
        smallest_positive_eigenvalue(
            state.hessian,
            cfg,
        )
    )

    deltas = np.empty(
        runs,
        dtype=float,
    )

    for run in range(runs):

        remove_indices = rng.choice(
            m,
            size=remove_n,
            replace=False,
        )

        random_edges = ablate_edges(
            state.edges,
            remove_indices,
        )

        random_hessian = build_enm_hessian(
            state.coords_A,
            random_edges,
            cfg.spring_k,
        )

        lambda_random = (
            smallest_positive_eigenvalue(
                random_hessian,
                cfg,
            )
        )

        deltas[run] = (
            lambda_random
            - lambda_native
        )

    return deltas


def empirical_two_sided_p(
    value: float,
    null_values: np.ndarray,
) -> float:
    """
    Randomization-test p-value.
    """

    extreme = np.count_nonzero(
        np.abs(null_values)
        >= abs(value)
    )

    return float(
        (1 + extreme)
        / (null_values.size + 1)
    )


