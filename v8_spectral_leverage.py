# FIRST-PRINCIPLES EDGE SPECTRAL SENSITIVITY
# ============================================================

def edge_spectral_leverage(
    coords_A: np.ndarray,
    edges: np.ndarray,
    positive_vectors: np.ndarray,
    positive_values: np.ndarray,
    cfg: Config,
) -> np.ndarray:
    """
    Rayleigh first-order eigenvalue sensitivity:

      d lambda_k / d w_ij
      =
      (v_i - v_j)^T P_ij (v_i - v_j)

    Since
        P_ij = u_ij u_ij^T,

    this becomes

      S_{e,k}
      =
      [u_ij^T (v_i-v_j)]^2.

    Global edge leverage:

      L_e = sum_k alpha_k S_{e,k}

    with
      alpha_k ∝ 1/lambda_k
    over the ten lowest positive modes.
    """

    k_count = min(
        cfg.soft_mode_count,
        positive_values.size,
    )

    # (3N, K) -> (N, 3, K)
    mode_vectors = positive_vectors[
        :, :k_count
    ].reshape(
        coords_A.shape[0],
        3,
        k_count,
    )

    vi = mode_vectors[
        edges[:, 0]
    ]

    vj = mode_vectors[
        edges[:, 1]
    ]

    delta_modes = vi - vj

    ri = coords_A[
        edges[:, 0]
    ]

    rj = coords_A[
        edges[:, 1]
    ]

    unit_vectors = rj - ri
    unit_vectors /= np.linalg.norm(
        unit_vectors,
        axis=1,
        keepdims=True,
    )

    # E x K
    projected = np.einsum(
        "ea,eak->ek",
        unit_vectors,
        delta_modes,
    )

    sensitivities = projected * projected

    # alpha_k ∝ 1/lambda_k
    alpha = 1.0 / np.maximum(
        positive_values[:k_count],
        cfg.density_floor,
    )

    alpha /= np.sum(alpha)

    # E
    leverage = sensitivities @ alpha

    if np.any(
        leverage < -cfg.eig_abs_tol
    ):
        raise RuntimeError(
            "Spectral leverage became negative."
        )

    return np.maximum(
        leverage,
        0.0,
    )


# ============================================================
# LEVERAGE DISTRIBUTION METRICS
# ============================================================

def spectral_gini(
    values: np.ndarray,
) -> float:
    """
    Gini coefficient for a nonnegative vector.
    """

    x = np.asarray(
        values,
        dtype=float,
    )

    if (
        x.size == 0
        or np.any(x < 0.0)
    ):
        raise ValueError(
            "Gini input must be nonempty and nonnegative."
        )

    total = float(
        np.sum(x)
    )

    if total <= 0.0:
        return 0.0

    x = np.sort(x)

    n = x.size
    rank = np.arange(
        1,
        n + 1,
        dtype=float,
    )

    return float(
        (
            2.0 * np.sum(rank * x)
            - (n + 1.0) * np.sum(x)
        )
        / (n * total)
    )


def leverage_metrics(
    leverage: np.ndarray,
) -> Tuple[
    float,
    np.ndarray,
    float,
    float,
]:
    total = float(
        np.sum(leverage)
    )

    if total <= 0.0:
        raise ValueError(
            "Leverage vector has zero total mass."
        )

    p = leverage / total

    # Edge-distribution IPR:
        # IPR_L = sum_e p_e^2
    ipr = float(
        np.sum(p * p)
    )

    # Effective edge participation ratio.
    pr = float(
        1.0 / ipr
    )

    gini = spectral_gini(
        leverage
    )

    return (
        gini,
        p,
        ipr,
        pr,
    )


