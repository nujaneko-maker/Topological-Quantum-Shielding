def load_ca_coords(pdbfile):
    coords = []
    residue_ids = []

    with open(
        pdbfile,
        "r",
        encoding="utf-8",
        errors="ignore"
    ) as f:

        for line in f:

            if not line.startswith("ATOM"):
                continue

            if line[12:16].strip() != "CA":
                continue

            try:
                x = float(line[30:38])
                y = float(line[38:46])
                z = float(line[46:54])
            except ValueError:
                continue

            resid = line[22:26].strip()

            coords.append([x, y, z])
            residue_ids.append(resid)

    coords = np.asarray(coords, dtype=float)

    if len(coords) == 0:
        raise ValueError(
            f"Không tìm thấy C-alpha trong {pdbfile}"
        )

    return coords, residue_ids


