CUTOFF_A = 7.0


def build_contact_graph(coords, cutoff=7.0):
    G = nx.Graph()

    N = len(coords)
    G.add_nodes_from(range(N))

    for i in range(N):
        for j in range(i + 1, N):

            d = np.linalg.norm(
                coords[j] - coords[i]
            )

            if 0.0 < d <= cutoff:
                G.add_edge(i, j)

    return G


