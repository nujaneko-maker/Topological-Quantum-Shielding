def build_hessian(coords, cutoff=7.0):
    N = len(coords)
    H = np.zeros((3*N, 3*N), dtype=float)

    for i in range(N):

        for j in range(i + 1, N):

            diff = coords[j] - coords[i]
            dist = np.linalg.norm(diff)

            if dist == 0.0 or dist > cutoff:
                continue

            u = diff / dist
            block = np.outer(u, u)

            ii = slice(3*i, 3*i+3)
            jj = slice(3*j, 3*j+3)

            H[ii, jj] -= block
            H[jj, ii] -= block

            H[ii, ii] += block
            H[jj, jj] += block

    H = 0.5 * (H + H.T)

    return H


