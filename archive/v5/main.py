def edge_trace(
    coords,
    G,
    width=2
):

    x = []
    y = []
    z = []

    for i, j in G.edges():

        x.extend([
            coords[i, 0],
            coords[j, 0],
            None
        ])

        y.extend([
            coords[i, 1],
            coords[j, 1],
            None
        ])

        z.extend([
            coords[i, 2],
            coords[j, 2],
            None
        ])

    return go.Scatter3d(
        x=x,
        y=y,
        z=z,
        mode="lines",
        line=dict(
            width=width
        ),
        hoverinfo="skip",
        name="ENM contacts"
    )


def node_trace(coords):

    N = len(coords)

    return go.Scatter3d(
        x=coords[:, 0],
        y=coords[:, 1],
        z=coords[:, 2],
        mode="markers",
        marker=dict(
            size=4
        ),
        text=[
            f"Residue {i+1}"
            for i in range(N)
        ],
        hovertemplate="%{text}<extra></extra>",
        name="Cα"
    )


