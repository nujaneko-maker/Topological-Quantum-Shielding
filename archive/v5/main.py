def randomize_graph_degree_preserving(
    G,
    swaps_factor=5,
    seed=42
):

    rng = np.random.default_rng(seed)

    R = G.copy()

    target_swaps = (
        swaps_factor *
        R.number_of_edges()
    )

    edges = list(R.edges())

    accepted = 0
    attempts = 0
    max_attempts = max(
        1000,
        50 * target_swaps
    )

    while (
        accepted < target_swaps
        and attempts < max_attempts
    ):

        attempts += 1

        if len(edges) < 2:
            break

        a, b = edges[
            rng.integers(len(edges))
        ]

        c, d = edges[
            rng.integers(len(edges))
        ]

        if len(
            {a, b, c, d}
        ) < 4:
            continue

        # Hai cách nối chéo
        choices = [
            (a, d, c, b),
            (a, c, d, b)
        ]

        new_edges = choices[
            rng.integers(2)
        ]

        e1 = (
            new_edges[0],
            new_edges[1]
        )

        e2 = (
            new_edges[2],
            new_edges[3]
        )

        if e1[0] == e1[1]:
            continue

        if e2[0] == e2[1]:
            continue

        if R.has_edge(*e1):
            continue

        if R.has_edge(*e2):
            continue

        R.remove_edge(a, b)
        R.remove_edge(c, d)

        R.add_edge(*e1)
        R.add_edge(*e2)

        accepted += 1

        edges = list(R.edges())

    return R, accepted


G_random, accepted = (
    randomize_graph_degree_preserving(
        G_target,
        swaps_factor=5,
        seed=42
    )
)

