def main():

    cfg = CFG

    rng = np.random.default_rng(
        cfg.seed
    )

    print("=" * 76)
    print("TQS v9.0 — 3D SYNTHETIC TOPOLOGICAL SUSCEPTIBILITY")
    print("=" * 76)

    # ------------------------------------------------------------
    # 1. 3D STRUCTURE
    # ------------------------------------------------------------

    coords = generate_3d_fold(
        cfg
    )

    edges = build_contact_graph(
        coords,
        cfg.cutoff_A
    )

    print(
        f"\n3D scaffold: "
        f"N={len(coords)}, "
        f"E={len(edges)}"
    )

    # ------------------------------------------------------------
    # 2. NULL TOPOLOGY
    # ------------------------------------------------------------

    random_edges, accepted = (
        maslov_sneppen(
            edges,
            cfg.N,
            cfg,
            rng
        )
    )

    assert np.array_equal(
        degree_sequence(
            edges,
            cfg.N
        ),
        degree_sequence(
            random_edges,
            cfg.N
        )
    )

    print(
        f"Maslov–Sneppen swaps: "
        f"{accepted:,}"
    )

    print(
        "Degree sequence invariant: TRUE"
    )

    # ------------------------------------------------------------
    # 3. NATIVE SYNTHETIC CYCLE
    # ------------------------------------------------------------

    print(
        "\n[1/5] Native θ sweep..."
    )

    native = theta_sweep(
        coords,
        edges,
        cfg
    )

    # ------------------------------------------------------------
    # 4. NULL SYNTHETIC CYCLE
    # ------------------------------------------------------------

    print(
        "[2/5] Null θ sweep..."
    )

    null = theta_sweep(
        coords,
        random_edges,
        cfg
    )

    # ------------------------------------------------------------
    # 5. TOP-LEVERAGE ABLATION
    # ------------------------------------------------------------

    L0 = native[
        "leverage_maps"
    ][0]

    top_indices = top_leverage_edges(
        edges,
        L0,
        cfg.ablation_fraction
    )

    top_edges = remove_edges(
        edges,
        top_indices
    )

    print(
        "[3/5] Top-leverage ablation θ sweep..."
    )

    top_ablation = theta_sweep(
        coords,
        top_edges,
        cfg
    )

    # ------------------------------------------------------------
    # 6. RANDOM MATCHED ABLATION
    # ------------------------------------------------------------

    number = len(top_indices)

    random_indices = rng.choice(
        len(edges),
        size=number,
        replace=False
    )

    random_edges_ablation = remove_edges(
        edges,
        random_indices
    )

    print(
        "[4/5] Random matched ablation θ sweep..."
    )

    random_ablation = theta_sweep(
        coords,
        random_edges_ablation,
        cfg
    )

    # ------------------------------------------------------------
    # 7. GAP TEST
    # ------------------------------------------------------------

    native_gap = gap_statistics(
        native
    )

    null_gap = gap_statistics(
        null
    )

    top_gap = gap_statistics(
        top_ablation
    )

    random_gap = gap_statistics(
        random_ablation
    )

    print("\n--- SYNTHETIC CYCLE GAP ---")

    print(
        f"Native min gap      : "
        f"{native_gap['min_gap']:.6e}"
    )

    print(
        f"Native gap CV       : "
        f"{native_gap['gap_cv']:.6f}"
    )

    print(
        f"Null min gap        : "
        f"{null_gap['min_gap']:.6e}"
    )

    print(
        f"Top-ablation min gap: "
        f"{top_gap['min_gap']:.6e}"
    )

    print(
        f"Random-ablation gap : "
        f"{random_gap['min_gap']:.6e}"
    )

    # ------------------------------------------------------------
    # 8. LINDBLAD BRIDGE
    # ------------------------------------------------------------

    H_spin, P_S, jumps = (
        build_spin_model(cfg)
    )

    # Mean normalized susceptibility.
    def normalized_susceptibility(
        sweep
    ):

        x = sweep[
            "susceptibility"
        ]

        return (
            x.mean()
            / max(
                native[
                    "susceptibility"
                ].mean(),
                1e-14
            )
        )

    s_native = (
        normalized_susceptibility(
            native
        )
    )

    s_null = (
        normalized_susceptibility(
            null
        )
    )

    s_top = (
        normalized_susceptibility(
            top_ablation
        )
    )

    s_random = (
        normalized_susceptibility(
            random_ablation
        )
    )

    # Phenomenological closure:
    #
    # larger spectral susceptibility
    # -> larger effective leakage rate.
    #
    # This is an explicit modeling assumption.
    def gamma_from_score(
        score
    ):

        return (
            cfg.gamma_floor
            + cfg.gamma_span
            * np.clip(
                score,
                0.0,
                1.0
            )
        )

    gamma_native = gamma_from_score(
        s_native
    )

    gamma_null = gamma_from_score(
        s_null
    )

    gamma_top = gamma_from_score(
        s_top
    )

    gamma_random = gamma_from_score(
        s_random
    )

    print(
        "\n[5/5] Lindblad trajectories..."
    )

    trajectories = {}

    for label, gamma in [
        ("Native", gamma_native),
        ("Maslov–Sneppen null", gamma_null),
        ("Top-leverage ablation", gamma_top),
        ("Random matched ablation", gamma_random)
    ]:

        t, Y = integrate_lindblad(
            gamma,
            H_spin,
            P_S,
            jumps,
            cfg
        )

        trajectories[label] = (
            t,
            Y
        )

        print(
            f"{label:25s} "
            f"gamma={gamma:.6f} μs^-1 "
            f"Y_S(5μs)={Y[-1]:.6f}"
        )

    # ------------------------------------------------------------
    # 9. 3D NATIVE LEVERAGE MAP
    # ------------------------------------------------------------

    plot_3d_leverage(
        coords,
        edges,
        native[
            "leverage_maps"
        ][0],
        "TQS v9 — 3D native spectral-leverage map"
    )

    # ------------------------------------------------------------
    # 10. 3D THETA ANIMATION
    # ------------------------------------------------------------

    animate_theta_3d(
        coords,
        edges,
        native["theta"],
        native["leverage_maps"]
    )

    # ------------------------------------------------------------
    # 11. DARK DASHBOARD
    # ------------------------------------------------------------

    dashboard(
        native,
        null,
        top_ablation,
        random_ablation,
        trajectories
    )

    # ------------------------------------------------------------
    # 12. FINAL DIAGNOSTIC
    # ------------------------------------------------------------

    native_ipr_range = (
        np.min(
            native["leverage_ipr"]
        ),
        np.max(
            native["leverage_ipr"]
        )
    )

    null_ipr_range = (
        np.min(
            null["leverage_ipr"]
        ),
        np.max(
            null["leverage_ipr"]
        )
    )

    print("\n" + "=" * 76)
    print("EPISTEMIC DIAGNOSTICS")
    print("=" * 76)

    print(
        "Native leverage IPR range: "
        f"{native_ipr_range}"
    )

    print(
        "Null leverage IPR range:   "
        f"{null_ipr_range}"
    )

