def remove_edges(
    edges,
    indices
):

    mask = np.ones(
        len(edges),
        dtype=bool
    )

    mask[indices] = False

    return edges[mask]


def top_leverage_edges(
    edges,
    leverage,
    fraction
):

    number = max(
        1,
        int(
            np.ceil(
                fraction * len(edges)
            )
        )
    )

    order = np.argsort(
        leverage
    )[::-1]

    return order[:number]


def ablated_gap_curve(
    coords,
    edges,
    remove_indices,
    cfg
):

    new_edges = remove_edges(
        edges,
        remove_indices
    )

    sweep = theta_sweep(
        coords,
        new_edges,
        cfg
    )

    return sweep


# ================================================================
# RANDOM ABLATION ENSEMBLE
# ================================================================

def random_ablation_ensemble(
    coords,
    edges,
    fraction,
    runs,
    rng,
    cfg
):

    m = len(edges)

    number = max(
        1,
        int(
            np.ceil(
                fraction * m
            )
        )
    )

    baseline = theta_sweep(
        coords,
        edges,
        cfg
    )

    baseline_gap = (
        baseline["spectra"][
            :,
            cfg.rigid_modes
        ][:, 0]
    )

    random_gap_shift = []

    for _ in range(runs):

        indices = rng.choice(
            m,
            size=number,
            replace=False
        )

        new_edges = remove_edges(
            edges,
            indices
        )

        sweep = theta_sweep(
            coords,
            new_edges,
            cfg
        )

        gap = (
            sweep["spectra"][
                :,
                cfg.rigid_modes
            ][:, 0]
        )

        random_gap_shift.append(
            np.mean(
                gap - baseline_gap
            )
        )

    return np.array(
        random_gap_shift
    )


