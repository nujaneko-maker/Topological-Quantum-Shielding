def gap_statistics(
    sweep
):

    spectra = sweep["spectra"]

    positive = spectra[
        :,
        CFG.rigid_modes:
    ]

    lowest = positive[:, 0]

    return {
        "min_gap": float(
            np.min(lowest)
        ),
        "max_gap": float(
            np.max(lowest)
        ),
        "mean_gap": float(
            np.mean(lowest)
        ),
        "gap_cv": float(
            np.std(lowest)
            / max(
                np.mean(lowest),
                1e-14
            )
        )
    }


