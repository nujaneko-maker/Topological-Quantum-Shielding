def animate_theta_3d(
    coords,
    edges,
    theta_grid,
    leverage_maps
):

    frames = []

    for frame_idx, theta in enumerate(
        theta_grid
    ):

        L = leverage_maps[
            frame_idx
        ]

        x = []
        y = []
        z = []

        for e, (i, j) in enumerate(edges):

            # Only display strongest edges
            if L[e] < np.quantile(
                L,
                0.90
            ):
                continue

            x += [
                coords[i, 0],
                coords[j, 0],
                None
            ]

            y += [
                coords[i, 1],
                coords[j, 1],
                None
            ]

            z += [
                coords[i, 2],
                coords[j, 2],
                None
            ]

        frames.append(
            go.Frame(
                data=[
                    go.Scatter3d(
                        x=x,
                        y=y,
                        z=z,
                        mode="lines",
                        line=dict(
                            width=5,
                            color="orange"
                        )
                    )
                ],
                name=str(frame_idx)
            )
        )

    first = frames[0].data

    fig = go.Figure(
        data=first,
        frames=frames
    )

    fig.update_layout(
        title=(
            "3D spectral-leverage evolution "
            "along synthetic θ dimension"
        ),
        template="plotly_dark",
        scene=dict(
            xaxis_title="X (Å)",
            yaxis_title="Y (Å)",
            zaxis_title="Z (Å)",
            aspectmode="data"
        ),
        updatemenus=[
            dict(
                type="buttons",
                buttons=[
                    dict(
                        label="▶ Play θ",
                        method="animate",
                        args=[
                            None,
                            {
                                "frame": {
                                    "duration": 300,
                                    "redraw": True
                                },
                                "fromcurrent": True
                            }
                        ]
                    )
                ]
            )
        ],
        sliders=[
            dict(
                steps=[
                    dict(
                        method="animate",
                        args=[
                            [str(i)],
                            {
                                "mode": "immediate",
                                "frame": {
                                    "duration": 0,
                                    "redraw": True
                                }
                            }
                        ],
                        label=f"{theta:.2f}"
                    )
                    for i, theta in enumerate(
                        theta_grid
                    )
                ],
                currentvalue={
                    "prefix": "θ = "
                }
            )
        ],
        width=1000,
        height=760
    )

    fig.show()


