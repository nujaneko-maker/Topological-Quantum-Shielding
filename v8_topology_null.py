def spin_z():

    return 0.5 * np.array(
        [
            [1, 0],
            [0, -1]
        ],
        dtype=complex
    )


def build_spin_model(cfg):

    I = np.eye(
        2,
        dtype=complex
    )

    Sz = spin_z()

    S1z = np.kron(
        Sz,
        I
    )

    S2z = np.kron(
        I,
        Sz
    )

    omega_B = (
        cfg.earth_B_T
        * cfg.electron_gamma_rad_s_T
        * 1e-6
    )

    A1 = (
        2.0
        * np.pi
        * cfg.A1_MHz
    )

    A2 = (
        2.0
        * np.pi
        * cfg.A2_MHz
    )

    H_product = (
        omega_B
        * (S1z + S2z)
        + A1 * S1z
        + A2 * S2z
    )

    up = np.array(
        [1, 0],
        dtype=complex
    )

    down = np.array(
        [0, 1],
        dtype=complex
    )

    singlet = (
        np.kron(up, down)
        - np.kron(down, up)
    ) / np.sqrt(2)

    Tplus = np.kron(
        up,
        up
    )

    Tzero = (
        np.kron(up, down)
        + np.kron(down, up)
    ) / np.sqrt(2)

    Tminus = np.kron(
        down,
        down
    )

    U = np.column_stack(
        [
            singlet,
            Tplus,
            Tzero,
            Tminus
        ]
    )

    H = (
        U.conj().T
        @ H_product
        @ U
    )

    P_S = np.zeros(
        (4, 4),
        dtype=complex
    )

    P_S[0, 0] = 1.0

    jumps = []

    for triplet in [1, 2, 3]:

        J = np.zeros(
            (4, 4),
            dtype=complex
        )

        J[triplet, 0] = 1.0

        jumps.append(J)

    return (
        H,
        P_S,
        jumps
    )


# ================================================================
# LINDBLAD
# ================================================================

def lindblad_rhs(
    rho,
    H,
    jumps,
    gamma
):

    drho = (
        -1j
        * (
            H @ rho
            - rho @ H
        )
    )

    for J in jumps:

        Jg = (
            np.sqrt(
                gamma / 3.0
            )
            * J
        )

        JJ = (
            Jg.conj().T
            @ Jg
        )

        drho += (
            Jg @ rho @ Jg.conj().T
            - 0.5
            * (
                JJ @ rho
                + rho @ JJ
            )
        )

    return drho


def positivity_guard(
    rho
):

    rho = 0.5 * (
        rho
        + rho.conj().T
    )

    tr = np.real(
        np.trace(rho)
    )

    rho /= tr

    values, vectors = la.eigh(
        rho
    )

    values = np.maximum(
        values,
        0.0
    )

    rho = (
        vectors
        * values
    ) @ vectors.conj().T

    rho = 0.5 * (
        rho
        + rho.conj().T
    )

    rho /= np.real(
        np.trace(rho)
    )

    return rho


def integrate_lindblad(
    gamma,
    H,
    P_S,
    jumps,
    cfg
):

    steps = int(
        round(
            cfg.total_time_us
            / cfg.dt_us
        )
    )

    times = np.linspace(
        0.0,
        cfg.total_time_us,
        steps + 1
    )

    rho = P_S.copy()

    Y = np.empty(
        steps + 1
    )

    Y[0] = np.real(
        np.trace(
            P_S @ rho
        )
    )

    for step in range(
        steps
    ):

        k1 = lindblad_rhs(
            rho,
            H,
            jumps,
            gamma
        )

        k2 = lindblad_rhs(
            rho + 0.5 * cfg.dt_us * k1,
            H,
            jumps,
            gamma
        )

        k3 = lindblad_rhs(
            rho + 0.5 * cfg.dt_us * k2,
            H,
            jumps,
            gamma
        )

        k4 = lindblad_rhs(
            rho + cfg.dt_us * k3,
            H,
            jumps,
            gamma
        )

        rho += (
            cfg.dt_us / 6.0
        ) * (
            k1
            + 2*k2
            + 2*k3
            + k4
        )

        rho = positivity_guard(
            rho
        )

        assert np.allclose(
            rho,
            rho.conj().T,
            atol=1e-9
        )

        assert np.isclose(
            np.trace(rho),
            1.0,
            atol=1e-9
        )

        assert np.min(
            la.eigvalsh(rho)
        ) >= -1e-9

        Y[step + 1] = np.real(
            np.trace(
                P_S @ rho
            )
        )

    return times, Y


