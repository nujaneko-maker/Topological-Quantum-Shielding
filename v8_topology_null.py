# 3D SYNTHETIC C-ALPHA FOLD
# ================================================================

def generate_3d_fold(cfg: Config) -> np.ndarray:

    t = np.linspace(
        0.0,
        cfg.turns * 2.0 * np.pi,
        cfg.N
    )

    radius = cfg.radius_A * (
        1.0
        + cfg.radial_modulation
        * np.sin(cfg.radial_warp_freq * t)
    )

    x = radius * np.cos(t)

    y = radius * np.sin(t)

    z = (
        cfg.pitch_A_per_rad * t
        + cfg.axial_warp_A
        * np.sin(cfg.axial_warp_freq * t)
    )

    coords = np.column_stack(
        [x, y, z]
    )

    coords -= coords.mean(axis=0)

    return coords


# ================================================================
# CONTACT GRAPH
# ================================================================

def build_contact_graph(
    coords: np.ndarray,
    cutoff: float
) -> np.ndarray:

    delta = (
        coords[:, None, :]
        - coords[None, :, :]
    )

    dist2 = np.einsum(
        "ijk,ijk->ij",
        delta,
        delta
    )

    i, j = np.triu_indices(
        len(coords),
        k=1
    )

    mask = (
        dist2[i, j]
        <= cutoff ** 2
    )

    return np.column_stack(
        [i[mask], j[mask]]
    ).astype(int)


def degree_sequence(
    edges: np.ndarray,
    n: int
) -> np.ndarray:

    return np.bincount(
        edges.reshape(-1),
        minlength=n
    )


# ================================================================
# MASLOV–SNEPPEN
# ================================================================

def maslov_sneppen(
    edges: np.ndarray,
    n: int,
    cfg: Config,
    rng: np.random.Generator
) -> Tuple[np.ndarray, int]:

    edge_list = [
        tuple(map(int, e))
        for e in edges
    ]

    edge_set = set(edge_list)

    target_swaps = max(
        20,
        cfg.swaps_per_edge * len(edge_list)
    )

    max_attempts = (
        target_swaps
        * cfg.max_attempt_factor
    )

    accepted = 0
    attempts = 0

    def canonical(a, b):

        return (
            (a, b)
            if a < b
            else
            (b, a)
        )

    while (
        accepted < target_swaps
        and attempts < max_attempts
    ):

        attempts += 1

        a_idx, b_idx = rng.choice(
            len(edge_list),
            size=2,
            replace=False
        )

        a, b = edge_list[a_idx]
        c, d = edge_list[b_idx]

        if len({a, b, c, d}) < 4:
            continue

        if rng.random() < 0.5:

            e1 = canonical(a, d)
            e2 = canonical(c, b)

        else:

            e1 = canonical(a, c)
            e2 = canonical(b, d)

        if (
            e1[0] == e1[1]
            or e2[0] == e2[1]
        ):
            continue

        old1 = canonical(a, b)
        old2 = canonical(c, d)

        if (
            e1 in edge_set
            or e2 in edge_set
        ):
            continue

        edge_set.remove(old1)
        edge_set.remove(old2)

        edge_set.add(e1)
        edge_set.add(e2)

        edge_list[a_idx] = e1
        edge_list[b_idx] = e2

        accepted += 1

    if accepted < target_swaps:

        raise RuntimeError(
            "Maslov-Sneppen sampler stalled: "
            f"{accepted}/{target_swaps} accepted."
        )

    randomized = np.array(
        sorted(edge_set),
        dtype=int
    )

    assert len(randomized) == len(edges)

    assert np.array_equal(
        degree_sequence(edges, n),
        degree_sequence(randomized, n)
    )

    return randomized, accepted


# ================================================================
# ENM HESSIAN
# ================================================================

def build_hessian(
    coords: np.ndarray,
    edges: np.ndarray,
    weights: np.ndarray,
    k: float
) -> np.ndarray:

    n = len(coords)

    H = np.zeros(
        (3 * n, 3 * n),
        dtype=float
    )

    ri = coords[edges[:, 0]]
    rj = coords[edges[:, 1]]

    delta = rj - ri

    norm = np.linalg.norm(
        delta,
        axis=1
    )

    unit = (
        delta
        / norm[:, None]
    )

    projectors = (
        np.einsum(
            "ea,eb->eab",
            unit,
            unit
        )
        * weights[:, None, None]
        * k
    )

    for e, (i, j) in enumerate(edges):

        si = slice(
            3 * i,
            3 * i + 3
        )

        sj = slice(
            3 * j,
            3 * j + 3
        )

        P = projectors[e]

        H[si, si] += P
        H[sj, sj] += P
        H[si, sj] -= P
        H[sj, si] -= P

    return 0.5 * (H + H.T)


# ================================================================
# SYNTHETIC THETA PHASE
# ================================================================

def edge_phase(
    coords: np.ndarray,
    edges: np.ndarray
) -> np.ndarray:

    """
    Geometry-derived phase assignment.

    It does NOT claim to be a physical Berry connection.

    It simply gives every edge a deterministic phase in S^1
    so that the mechanical operator becomes a periodic family.
    """

    midpoints = (
        coords[edges[:, 0]]
        + coords[edges[:, 1]]
    ) / 2.0

    phi = np.arctan2(
        midpoints[:, 1],
        midpoints[:, 0]
    )

    return phi


def theta_weights(
    theta: float,
    phases: np.ndarray,
    amplitude: float
) -> np.ndarray:

    weights = (
        1.0
        + amplitude
        * np.cos(
            theta + phases
        )
    )

    # Strictly positive spring weights.
    return np.maximum(
        weights,
        1e-4
    )


# ================================================================
# DIAGONALIZATION
# ================================================================

def diagonalize(
    H: np.ndarray,
    cfg: Config
):

    values, vectors = la.eigh(
        H
    )

    scale = max(
        1.0,
        np.max(np.abs(values))
    )

    tol = max(
        cfg.eig_abs_tol,
        cfg.eig_rel_tol * scale
    )

    if np.min(values) < -10.0 * tol:

        raise RuntimeError(
            "Hessian lost positive-semidefinite structure."
        )

    rigid = values[:cfg.rigid_modes]

    if not np.all(
        np.abs(rigid)
        < 10.0 * tol
    ):

        raise RuntimeError(
            "Six rigid-body modes were not identified."
        )

    positive = values[
        values > tol
    ]

    positive_vectors = vectors[
        :,
        values > tol
    ]

    return (
        values,
        vectors,
        positive,
        positive_vectors,
        tol
    )


# ================================================================
# EDGE SPECTRAL SUSCEPTIBILITY
# ================================================================

def spectral_leverage(
    coords: np.ndarray,
    edges: np.ndarray,
    positive_values: np.ndarray,
    positive_vectors: np.ndarray,
    cfg: Config
) -> np.ndarray:

    K = min(
        cfg.soft_modes,
        len(positive_values)
    )

    modes = positive_vectors[
        :, :K
    ].reshape(
        len(coords),
        3,
        K
    )

    vi = modes[
        edges[:, 0]
    ]

    vj = modes[
        edges[:, 1]
    ]

    delta_modes = vi - vj

    ri = coords[
        edges[:, 0]
    ]

    rj = coords[
        edges[:, 1]
    ]

    u = rj - ri

    u /= np.linalg.norm(
        u,
        axis=1,
        keepdims=True
    )

    projection = np.einsum(
        "ea,eak->ek",
        u,
        delta_modes
    )

    sensitivity = (
        projection ** 2
    )

    alpha = (
        1.0
        / np.maximum(
            positive_values[:K],
            1e-14
        )
    )

    alpha /= alpha.sum()

    leverage = (
        sensitivity @ alpha
    )

    return leverage


# ================================================================
# LEVERAGE METRICS
# ================================================================

def gini(x):

    x = np.asarray(
        x,
        dtype=float
    )

    x = np.sort(
        np.maximum(x, 0)
    )

    if np.sum(x) == 0:
        return 0.0

    n = len(x)

    return float(
        (
            2.0
            * np.sum(
                np.arange(1, n + 1)
                * x
            )
            - (n + 1)
            * np.sum(x)
        )
        / (
            n * np.sum(x)
        )
    )


def leverage_ipr(
    L
):

    p = (
        L
        / np.sum(L)
    )

    return float(
        np.sum(p ** 2)
    )


# ================================================================
# THETA SWEEP
# ================================================================

def theta_sweep(
    coords: np.ndarray,
    edges: np.ndarray,
    cfg: Config
):

    theta_grid = np.linspace(
        0.0,
        2.0 * np.pi,
        cfg.theta_points,
        endpoint=False
    )

    phases = edge_phase(
        coords,
        edges
    )

    spectra = []
    ipr_values = []
    gini_values = []
    susceptibility = []
    leverage_maps = []
    mode_profiles = []

    for theta in theta_grid:

        weights = theta_weights(
            theta,
            phases,
            cfg.theta_amplitude
        )

        H = build_hessian(
            coords,
            edges,
            weights,
            cfg.spring_k
        )

        (
            values,
            vectors,
            positive,
            positive_vectors,
            tol
        ) = diagonalize(
            H,
            cfg
        )

        L = spectral_leverage(
            coords,
            edges,
            positive,
            positive_vectors,
            cfg
        )

        ipr = leverage_ipr(L)

        G = gini(L)

        # Lowest positive spectral gap.
        gap = positive[0]

        # Susceptibility:
        # total soft-mode weighted leverage.
        chi = np.sum(L)

        spectra.append(
            values
        )

        ipr_values.append(
            ipr
        )

        gini_values.append(
            G
        )

        susceptibility.append(
            chi
        )

        leverage_maps.append(
            L
        )

        # Localization of the first positive mode.
        v = positive_vectors[
            :, 0
        ]

        p = v ** 2

        mode_profiles.append(
            np.sum(p ** 2)
        )

    return {
        "theta": theta_grid,
        "spectra": np.array(spectra),
        "leverage_ipr": np.array(ipr_values),
        "leverage_gini": np.array(gini_values),
        "susceptibility": np.array(susceptibility),
        "leverage_maps": leverage_maps,
        "mode_ipr": np.array(mode_profiles),
    }


